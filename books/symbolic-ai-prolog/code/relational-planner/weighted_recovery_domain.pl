%% weighted_recovery_schemas(-Schemas) is det.
%
% Synthetic teaching domain for Chapter 9.  It deliberately contains a
% one-action remote recovery that costs more than a two-action on-site path.
% Taxi, shuttle, and bus produce the same canonical site state at different or
% equal costs so best-cost replacement and stale/dominated entries are visible.
weighted_recovery_schemas(
    [ schema(remote_restore,
             remote_restore(Node),
             [ failed(Node), remote_access(Node) ],
             [ restored(Node) ],
             [ failed(Node) ]),
      schema(taxi,
             taxi(Tech, From, Site),
             [ tech_at(Tech, From), route(From, Site) ],
             [ tech_at(Tech, Site) ],
             [ tech_at(Tech, From) ]),
      schema(shuttle,
             shuttle(Tech, From, Site),
             [ tech_at(Tech, From), route(From, Site) ],
             [ tech_at(Tech, Site) ],
             [ tech_at(Tech, From) ]),
      schema(bus,
             bus(Tech, From, Site),
             [ tech_at(Tech, From), route(From, Site) ],
             [ tech_at(Tech, Site) ],
             [ tech_at(Tech, From) ]),
      schema(onsite_restore,
             onsite_restore(Tech, Node),
             [ tech_at(Tech, Site),
               hosts(Site, Node),
               failed(Node)
             ],
             [ restored(Node) ],
             [ failed(Node) ])
    ]).

weighted_recovery_costed_schemas(Costed) :-
    weighted_recovery_schemas(
        [ Remote,
          Taxi,
          Shuttle,
          Bus,
          Onsite
        ]),
    Costed = [ costed(Remote, 12),
               costed(Taxi, 2),
               costed(Shuttle, 1),
               costed(Bus, 1),
               costed(Onsite, 10)
             ].

weighted_recovery_initial_state(
    [ failed(node7),
      hosts(site_a, node7),
      remote_access(node7),
      route(depot, site_a),
      tech_at(tech1, depot),
      ticket_open(inc7)
    ]).

weighted_recovery_goal([restored(node7)]).
weighted_recovery_impossible_goal([restored(node999)]).

